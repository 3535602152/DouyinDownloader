"""Regenerate the checked-in offline editor schema: python -m scripts.export_settings_schema."""
from __future__ import annotations

import json
from pathlib import Path

from storage.preferences import schema


def javascript() -> str:
    payload = json.dumps(schema(), ensure_ascii=False, indent=2)
    return "// Generated by python -m scripts.export_settings_schema; edit storage/preferences.py.\nwindow.SettingsSchema = " + payload + "\n"


if __name__ == "__main__":
    target = Path(__file__).resolve().parents[1] / "gui/web/settings-schema.js"
    target.write_text(javascript(), encoding="utf-8")
